export function detectInitialLang(): LangCode {
  const saved = localStorage.getItem('fleet_lang') as LangCode | null;
  if (saved && saved in MESSAGES) return saved;
  const nav = (navigator.language || 'zh-CN').toLowerCase();
  if (nav.startsWith('zh-tw') || nav.startsWith('zh-hk')) return 'zh-TW';
  if (nav.startsWith('zh')) return 'zh-CN';
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('ko')) return 'ko';
  return 'en';
}

export function tr(lang: LangCode, key: string): string {
  return MESSAGES[lang]?.[key] ?? MESSAGES['zh-CN'][key] ?? key;
}
